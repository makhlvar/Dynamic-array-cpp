#pragma once
#include <cstddef>//size_t
#include <stdexcept>//std::out_of_range, std::invalid_argument
#include <new>//std::bad_alloc

class DynamicArray{//класс динамического массива
    private:
    int* ptr;//указатель на данные
    std::size_t size;//размер массива(данных)
    std::size_t capacity;//запас, чуть больше чем наш массив
    public:
    DynamicArray();//конструктор
    //Постусловие: size == 0, ptr == nullptr
    //Создаёт "пустой" массив, не владеющий памятью

    DynamicArray(std::size_t s);//конструктор,получающий на вход размер массива
    //Предусловие: s >= 0 тк отрицательный размер не имеет смысла
    //Постусловие: size == s, ptr указывает на массив из s нулей
    //Если s == 0 — ведёт себя как конструктор по умолчанию.
    //Часть 2 — исключения: может бросить std::bad_alloc,
    //если new[] не сможет выделить память

    ~DynamicArray();//деструктор
    //Освобождает память, выделенную под массив (если она была)
    //После завершения работы деструктора объект невалиден

    void PrintArray() const;// [ЧАСТЬ 2] добавлен const — метод не меняет объект
    //ф-ция вывода всех значений массива
    //Выводит все size элементов массива в одну строку через пробел,
    //затем переводит курсор на новую строку
    //Не изменяет состояние объекта

    int get(std::size_t index)const;//Геттер
    //Проверяет выход за границы массива
    //Часть 2: бросает std::out_of_range, если index >= size
    //Возвращает значение элемента по индексу index

    void set(std::size_t index,int value);//сеттер, проверяющий:
    //входной индекс на выход за границы массива
    //входящее значение на принадлежность к промежутку
    //от −100 до 100 включительно
    //Часть 2: бросает std::out_of_range, если index >= size
    //Часть 2: бросает std::invalid_argument, если value вне [-100; 100]
    //Постусловие: ptr[index] == value

    DynamicArray(const DynamicArray&);//конструктор копирования
    //Создаёт глубокую копию другого массива
    //Постусловие: this->size == other.size,
    //this->ptr указывает на собственную копию данных other
    //Часть 2: может бросить std::bad_alloc

    void append(int value);//операция добавления значения в конец массива
    //с расширением его размера
    //Добавляемое значение проверено на принадлежность к промежутку −100…100
    //Часть 2: бросает std::invalid_argument, если value вне [-100; 100]
    //Часть 2: может бросить std::bad_alloc при выделении нового массива
    //Постусловие: size увеличился на 1, последний элемент == value,
    //ptr указывает на новый участок памяти, старый освобождён

    void add(const DynamicArray&);
    //изм больший массив
    //*this = this + other
    //если other > то оставшиеся эл-ты игнорируются 
    //Если размеры не совпадают other дополняется нулями

    void substract(const DynamicArray&);
    //*this = this - other
};